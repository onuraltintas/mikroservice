// pool-texts/v1 için dört soru düzeltmesi (27.11.2026, yayın sonrası içerik incelemesi).
// fixes.json yalnız değişen soruların yeni hâlini tutar; eski hâli ../v1/questions.json'dan okunur.
// apply.sql yalnız eski hâlindeki satırı günceller, rollback.sql yalnız yeni hâlindekini geri döndürür;
// satır üçüncü bir hâldeyse (elle düzenlenmişse) ikisi de hiçbir şey değiştirmeden durur.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { questionProblems, textProblems, surfaceCues, MAX_SURFACE_CUE } from '../../pool-questions/rules.mjs';

const directory = dirname(fileURLToPath(import.meta.url));
const v1 = name => JSON.parse(readFileSync(join(directory, '../v1', name), 'utf8'));
export const ACTOR = 'pool-texts-v1-fix1';
export const FIELDS = [
  ['questionText', 'question_text'], ['explanation', 'explanation'],
  ['optionA', 'option_a'], ['optionB', 'option_b'], ['optionC', 'option_c'], ['optionD', 'option_d'],
  ['correctAnswer', 'correct_answer'],
];
const CHILD = '10000000-0000-0000-0000-000000000001';
const LETTERS = ['A', 'B', 'C', 'D'];

export function build() {
  const texts = v1('texts.json'), before = v1('questions.json');
  const fixes = JSON.parse(readFileSync(join(directory, 'fixes.json'), 'utf8'));
  const problems = [], pairs = [];
  const byId = new Map(before.map(row => [row.id, row]));
  const textById = new Map(texts.map(text => [text.id, text]));
  if (new Set(fixes.map(fix => fix.id)).size !== fixes.length) problems.push('aynı soru iki kez');
  for (const fix of fixes) {
    const old = byId.get(fix.id);
    if (!old) { problems.push(`${fix.id}: v1'de yok`); continue; }
    const row = { ...old };
    for (const [key] of FIELDS) row[key] = fix[key];
    if (row.correctAnswer !== old.correctAnswer) problems.push(`${fix.id}: cevap harfi değişmemeli`);
    if (FIELDS.every(([key]) => row[key] === old[key])) problems.push(`${fix.id}: değişiklik yok`);
    const text = textById.get(old.readingTextId);
    const correct = row[`option${row.correctAnswer}`];
    const wrong = LETTERS.filter(letter => letter !== row.correctAnswer).map(letter => row[`option${letter}`]);
    const question = { p: row.paragraph, type: row.type, bloom: row.bloomLevel, text: row.questionText, correct, wrong, explanation: row.explanation };
    for (const problem of questionProblems(question, text.content.trim().split(/\r?\n\s*\r?\n/u).length)) problems.push(`${text.title} #${row.orderIndex}: ${problem}`);
    pairs.push({ old, row, text });
  }
  const after = before.map(row => pairs.find(pair => pair.old.id === row.id)?.row ?? row);
  for (const text of new Set(pairs.map(pair => pair.text))) {
    const questions = after.filter(row => row.readingTextId === text.id).map(row => ({
      p: row.paragraph, type: row.type, bloom: row.bloomLevel, text: row.questionText,
      correct: row[`option${row.correctAnswer}`],
    }));
    const young = text.ageGroupId === CHILD && text.level <= 2;
    for (const problem of textProblems(questions, text.content.trim().split(/\r?\n\s*\r?\n/u).length, { young })) problems.push(`${text.title}: ${problem}`);
  }
  const cues = surfaceCues(after.map(row => ({
    options: LETTERS.map(letter => row[`option${letter}`]), answer: LETTERS.indexOf(row.correctAnswer), text: textById.get(row.readingTextId).content,
  })));
  for (const [name, value] of Object.entries(cues)) if (value > MAX_SURFACE_CUE[name]) problems.push(`paket ipucu ${name} ${value.toFixed(3)}`);
  return { pairs, after, cues, problems };
}

const sql = value => `'${String(value).replaceAll("'", "''")}'`;
const columns = FIELDS.map(([, column]) => column);

function script({ pairs }, direction) {
  const forward = direction === 'apply';
  const from = pair => (forward ? pair.old : pair.row), to = pair => (forward ? pair.row : pair.old);
  const actor = forward ? ACTOR : `${ACTOR}-rollback`;
  const values = pairs.map(pair => `    ('${pair.old.id}'::uuid, ${FIELDS.map(([key]) => sql(from(pair)[key])).join(', ')},\n     ${FIELDS.map(([key]) => sql(to(pair)[key])).join(', ')})`);
  const same = prefix => columns.map(column => `q.${column} IS NOT DISTINCT FROM f.${prefix}_${column}`).join(' AND ');
  return `-- Generated by content-packs/pool-texts/v1-fix1/generate.mjs. Do not edit by hand.
-- ${forward ? 'pool-texts/v1 içindeki 4 sorunun metnini ve seçeneklerini düzeltir.' : 'pool-texts/v1-fix1 düzeltmesini geri alır: 4 soru eski hâline döner.'} Yalnız speedreading_owned_db.
-- Tekrar çalıştırmak güvenli: hedef hâldeki soru atlanır. Bir soru yoksa ya da elle değiştirilmişse hiçbir şey değiştirmeden durur.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '60s';

CREATE TEMP TABLE fix (
    id uuid PRIMARY KEY,
    ${columns.map(column => `from_${column} text`).join(', ')},
    ${columns.map(column => `to_${column} text`).join(', ')}
) ON COMMIT DROP;
INSERT INTO fix VALUES
${values.join(',\n')};

DO $$
DECLARE
    unexpected integer;
    changed integer;
BEGIN
    SELECT count(*) INTO unexpected FROM fix f
    LEFT JOIN speed_reading.reading_questions q ON q.id = f.id
    WHERE q.id IS NULL OR NOT ((${same('from')}) OR (${same('to')}));
    IF unexpected <> 0 THEN
        RAISE EXCEPTION '${actor}: % question(s) missing or edited by hand; nothing changed', unexpected;
    END IF;

    UPDATE speed_reading.reading_questions q
    SET ${columns.map(column => `${column} = f.to_${column}`).join(', ')},
        updated_at = CURRENT_TIMESTAMP, updated_by = '${actor}'
    FROM fix f WHERE q.id = f.id AND ${same('from')};
    GET DIAGNOSTICS changed = ROW_COUNT;
    RAISE NOTICE '${actor}: % question(s) ${forward ? 'fixed' : 'restored'}, % already done', changed, ${pairs.length} - changed;
END $$;

COMMIT;
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const result = build();
  if (result.problems.length) {
    console.error(result.problems.join('\n'));
    process.exit(1);
  }
  writeFileSync(join(directory, 'apply.sql'), script(result, 'apply'));
  writeFileSync(join(directory, 'rollback.sql'), script(result, 'rollback'));
  const percent = value => `%${(value * 100).toFixed(1).replace('.', ',')}`;
  console.log(`${result.pairs.length} soru; paket ipuçları: en uzun ${percent(result.cues.longest)}, en kısa ${percent(result.cues.shortest)}, örtüşme ${percent(result.cues.overlap)}`);
}
