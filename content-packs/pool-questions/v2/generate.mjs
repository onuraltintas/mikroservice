// Ortak havuza taşınan 79 Serbest Okuma metnine 8'er anlama sorusu (26.11.2026).
// Metinler canlı anlık görüntüden okunur (content-packs/live-snapshot/20261126); sorular source/*.json içinde metin numarasına
// göre yazılır (TARGETS kimliğe göre sıralı; 1 = ilk kimlik). Her soru p (dayandığı paragraf), type, bloom, text, correct, wrong[3],
// explanation alanlarını taşır. Cevap harfleri letterPlan ile her metinde A–D ikişer kez olacak biçimde yerleştirilir.
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { gunzipSync } from 'node:zlib';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { arrange, letterPlan, questionProblems, textProblems } from '../rules.mjs';

const directory = dirname(fileURLToPath(import.meta.url));
const snapshot = resolve(directory, '../../live-snapshot/20261126');
const moves = JSON.parse(readFileSync(resolve(directory, '../../shared-pool/v1/moves.json'), 'utf8')).moves;
export const TARGETS = moves.filter(move => move.source === 'FreeReading').map(move => move.id).sort();
export const ACTOR = 'pool-questions-v2';
export const textId = number => TARGETS[Number(number) - 1];

export const paragraphs = content => content.trim().split(/\r?\n\s*\r?\n/u);
export function loadTexts() {
  const rows = gunzipSync(readFileSync(join(snapshot, 'texts.jsonl.gz'))).toString('utf8').split('\n').filter(Boolean).map(line => JSON.parse(line));
  return new Map(rows.filter(row => TARGETS.includes(row.id)).map(row => [row.id, row]));
}
export function loadSource() {
  const source = new Map();
  for (const file of readdirSync(join(directory, 'source')).filter(name => name.endsWith('.json')).sort()) {
    for (const [number, questions] of Object.entries(JSON.parse(readFileSync(join(directory, 'source', file), 'utf8')))) {
      const id = textId(number);
      if (!id) throw new Error(`text ${number} is not a target`);
      if (source.has(id)) throw new Error(`text ${number} is written twice`);
      source.set(id, questions);
    }
  }
  return source;
}

export function build({ partial = false } = {}) {
  const texts = loadTexts(), source = loadSource(), rows = [], problems = [];
  let serial = 0;
  for (const id of TARGETS) {
    const text = texts.get(id), questions = source.get(id);
    if (!questions) { if (!partial) problems.push(`${id}: soru yok`); continue; }
    const count = paragraphs(text.content).length;
    const young = text.target_age_group_id === '10000000-0000-0000-0000-000000000001' && text.difficulty_level <= 2;
    for (const problem of textProblems(questions, count, { young })) problems.push(`${String(TARGETS.indexOf(id) + 1).padStart(3, '0')}: ${problem}`);
    const plan = letterPlan(id);
    questions.forEach((question, index) => {
      for (const problem of questionProblems(question, count)) problems.push(`${String(TARGETS.indexOf(id) + 1).padStart(3, '0')} #${index + 1}: ${problem}`);
      const { options, answer } = arrange(question, plan[index]);
      serial++;
      rows.push({ id: `d7b50000-0000-5000-8000-${String(serial).padStart(12, '0')}`, readingTextId: id,
        contentMd5: createHash('md5').update(text.content, 'utf8').digest('hex'), paragraph: question.p,
        questionText: question.text, type: question.type, bloomLevel: question.bloom, difficultyLevel: text.difficulty_level,
        explanation: question.explanation, optionA: options[0], optionB: options[1], optionC: options[2], optionD: options[3],
        correctAnswer: answer, orderIndex: index });
    });
  }
  return { rows, problems };
}

const sql = value => typeof value === 'number' ? String(value) : `'${String(value).replaceAll("'", "''")}'`;
export function render(rows) {
  const checks = [...new Map(rows.map(row => [row.readingTextId, row.contentMd5])).entries()];
  const apply = `-- Generated by content-packs/pool-questions/v2/generate.mjs. Do not edit by hand.
-- Ortak havuza taşınan ${checks.length} Serbest Okuma metnine 8'er anlama sorusu (toplam ${rows.length}). Yalnız speedreading_owned_db.
-- ${checks.length} metnin hepsi silinmemiş ve içeriği aynı (md5) değilse ya da metinlerde bu paketten olmayan soru varsa hiçbir şey
-- değiştirmeden durur. Tekrar çalıştırmak güvenli: kimlikler sabit, var olan satır atlanır; geri almayla silinenler geri gelir.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '60s';

CREATE TEMP TABLE pool_question_text (id uuid PRIMARY KEY, content_md5 text NOT NULL) ON COMMIT DROP;
INSERT INTO pool_question_text (id, content_md5) VALUES
${checks.map(([id, md5]) => `    ('${id}'::uuid, '${md5}')`).join(',\n')};

DO $$
DECLARE matched integer; foreign_questions integer;
BEGIN
    SELECT count(*) INTO matched FROM pool_question_text c
    JOIN speed_reading.reading_texts t ON t.id = c.id AND NOT t.is_deleted AND md5(t.content) = c.content_md5;
    IF matched <> ${checks.length} THEN
        RAISE EXCEPTION 'pool-questions/v2: % of ${checks.length} texts match; nothing changed', matched;
    END IF;
    SELECT count(*) INTO foreign_questions FROM speed_reading.reading_questions q JOIN pool_question_text c ON c.id = q.reading_text_id
    WHERE NOT q.is_deleted AND q.created_by IS DISTINCT FROM '${ACTOR}';
    IF foreign_questions <> 0 THEN
        RAISE EXCEPTION 'pool-questions/v2: % other question(s) already exist on these texts; nothing changed', foreign_questions;
    END IF;
END $$;

CREATE TEMP TABLE pool_question (
    id uuid PRIMARY KEY, reading_text_id uuid NOT NULL, question_text text NOT NULL, type integer NOT NULL,
    bloom_level integer NOT NULL, difficulty_level integer NOT NULL, explanation text NOT NULL,
    option_a text NOT NULL, option_b text NOT NULL, option_c text NOT NULL, option_d text NOT NULL,
    correct_answer text NOT NULL, order_index integer NOT NULL
) ON COMMIT DROP;
INSERT INTO pool_question
    (id, reading_text_id, question_text, type, bloom_level, difficulty_level, explanation,
     option_a, option_b, option_c, option_d, correct_answer, order_index)
VALUES
${rows.map(row => `    ('${row.id}'::uuid, '${row.readingTextId}'::uuid, ${sql(row.questionText)}, ${row.type}, ${row.bloomLevel}, ${row.difficultyLevel}, ${sql(row.explanation)},
     ${sql(row.optionA)}, ${sql(row.optionB)}, ${sql(row.optionC)}, ${sql(row.optionD)}, '${row.correctAnswer}', ${row.orderIndex})`).join(',\n')};

DO $$
DECLARE added integer; restored integer;
BEGIN
    INSERT INTO speed_reading.reading_questions
        (id, reading_text_id, question_text, type, bloom_level, difficulty_level, explanation,
         option_a, option_b, option_c, option_d, correct_answer, order_index, created_at, created_by, is_deleted)
    SELECT id, reading_text_id, question_text, type, bloom_level, difficulty_level, explanation,
           option_a, option_b, option_c, option_d, correct_answer, order_index, CURRENT_TIMESTAMP, '${ACTOR}', FALSE
    FROM pool_question source
    WHERE NOT EXISTS (SELECT 1 FROM speed_reading.reading_questions target WHERE target.id = source.id);
    GET DIAGNOSTICS added = ROW_COUNT;
    UPDATE speed_reading.reading_questions target
    SET is_deleted = FALSE, deleted_at = NULL, deleted_by = NULL, updated_at = CURRENT_TIMESTAMP, updated_by = '${ACTOR}'
    FROM pool_question source
    WHERE target.id = source.id AND target.is_deleted AND target.created_by = '${ACTOR}' AND target.deleted_by = '${ACTOR}-rollback';
    GET DIAGNOSTICS restored = ROW_COUNT;
    RAISE NOTICE 'pool-questions/v2: % question(s) added, % restored', added, restored;
END $$;

COMMIT;
`;
  const rollback = `-- Generated by content-packs/pool-questions/v2/generate.mjs. Do not edit by hand.
-- Yalnız bu paketin ${rows.length} sorusunu yumuşak siler.
BEGIN;
DO $$
DECLARE removed integer;
BEGIN
    UPDATE speed_reading.reading_questions
    SET is_deleted = TRUE, deleted_at = CURRENT_TIMESTAMP, deleted_by = '${ACTOR}-rollback',
        updated_at = CURRENT_TIMESTAMP, updated_by = '${ACTOR}-rollback'
    WHERE NOT is_deleted AND created_by = '${ACTOR}' AND id IN (
${rows.map(row => `        '${row.id}'::uuid`).join(',\n')});
    GET DIAGNOSTICS removed = ROW_COUNT;
    RAISE NOTICE 'pool-questions/v2 rollback: % question(s) soft-deleted', removed;
END $$;
COMMIT;
`;
  return { apply, rollback };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const partial = process.argv.includes('--check');
  const { rows, problems } = build({ partial });
  if (problems.length) { console.error(problems.join('\n')); process.exitCode = 1; }
  if (partial) { console.log(`${rows.length / 8} text(s) checked, ${problems.length} problem(s)`); }
  else if (!problems.length) {
    const { apply, rollback } = render(rows);
    writeFileSync(join(directory, 'questions.json'), JSON.stringify(rows, null, 2) + '\n');
    writeFileSync(join(directory, 'apply.sql'), apply);
    writeFileSync(join(directory, 'rollback.sql'), rollback);
    console.log(`Generated ${rows.length} questions for ${rows.length / 8} texts.`);
  }
}
