#!/usr/bin/env node
// KM3 minutes pack v1 (01.11.2026, user decision "sınırı yükselt"): the per-topic limit goes from 1440 to 4320 minutes.
// Builds topics.csv, check.sql, apply.sql, verify.sql and the README table from the KM3 model
// (content-packs/coaching-catalog-km3/build.mjs --json): every KM3 topic whose stored 1440 minutes were capped, with the
// uncapped estimate and the outcome note both limits produce.
//   node build.mjs           writes the files
//   node build.mjs --check   exits 1 when one of them is out of date
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const dir = fileURLToPath(new URL('.', import.meta.url));
const km3 = fileURLToPath(new URL('../../coaching-catalog-km3/build.mjs', import.meta.url));
const built = spawnSync(process.execPath, [km3, '--json'], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
if (built.status !== 0) { console.error(built.stderr); process.exit(1); }
const model = JSON.parse(built.stdout);
const examLabel = { AGS: 'AGS', OABT: 'ÖABT', YDS: 'YDS', YOKDIL: 'YÖKDİL' };
const rows = model.lessons.flatMap(l => l.topics.map(t => ({ ...t, exam: examLabel[l.exam], lesson: l.name })))
  .filter(t => t.previousMinutes !== t.minutes);
for (const t of rows)
  if (t.previousMinutes !== 1440 || t.minutes <= 1440 || t.minutes > 4320) throw new Error(`unexpected minutes for ${t.code}`);

const SOURCE = 'coaching-catalog-km3', PACK = 'coaching-catalog-km3-minutes/v1', AGENT = `content-packs/${PACK}`;
const REASON = 'KM3 konu süreleri 4320 dakika konu sınırıyla yeniden hesaplandı (01.11.2026 kararı: sınırı yükselt; konular bölünmedi).';
const q = v => v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`;
const csvCell = v => { const s = String(v); return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s; };

const csv = ['topic_id,outcome_id,topic_code,exam,old_minutes,new_minutes,topic']
  .concat(rows.map(t => [t.topicId, t.outcomeId, t.code, t.exam, t.previousMinutes, t.minutes, t.name].map(csvCell).join(','))).join('\n') + '\n';

const dataSelect = `SELECT topic_id::uuid, outcome_id::uuid, code, old_minutes, new_minutes, old_notes, new_notes FROM (VALUES
${rows.map(t => `    (${[t.topicId, t.outcomeId, t.code, t.previousMinutes, t.minutes, t.previousOutcomeNotes, t.outcomeNotes].map(q).join(', ')})`).join(',\n')}
) v (topic_id, outcome_id, code, old_minutes, new_minutes, old_notes, new_notes)`;

// The stored state of each row and why it differs from what the pack expects (NULL = as expected).
const stateSelect = `SELECT k.*, t."Name" topic_name, t."EstimatedMinutes" minutes, t."YieldWeight" yield_weight, o."Notes" notes,
    e."Id" estimate_id, e."Number" estimate_number, e."LearningMinutes" learning, e."PracticeMinutes" practice, e."CheckMinutes" "check",
    e."Confidence" confidence, e."LearningMinutes" + e."PracticeMinutes" + e."CheckMinutes" estimate_total,
    (SELECT max(x."Number") FROM coaching.outcome_duration_estimates x WHERE x."OutcomeId" = k.outcome_id) max_number,
    CASE WHEN t."Id" IS NULL OR t."Source" <> '${SOURCE}' OR t."SourceId" <> k.code THEN 'topic is missing or not a KM3 record'
         WHEN t."EstimatedMinutes" IS DISTINCT FROM k.old_minutes AND t."EstimatedMinutes" IS DISTINCT FROM k.new_minutes
             THEN 'topic minutes ' || coalesce(t."EstimatedMinutes"::text, 'empty')
         WHEN o."Id" IS NULL THEN 'outcome is missing'
         WHEN o."Notes" IS DISTINCT FROM k.old_notes AND o."Notes" IS DISTINCT FROM k.new_notes THEN 'outcome note was edited'
         WHEN m."IsApproved" IS DISTINCT FROM true THEN 'topic–outcome link is missing or not approved'
         WHEN e."Id" IS NOT NULL AND e."LearningMinutes" + e."PracticeMinutes" + e."CheckMinutes" NOT IN (k.old_minutes, k.new_minutes)
             THEN 'published duration version ' || e."Number" || ' has ' || (e."LearningMinutes" + e."PracticeMinutes" + e."CheckMinutes") || ' min'
    END drift
FROM km3m k
LEFT JOIN coaching.study_catalog_topics t ON t."Id" = k.topic_id
LEFT JOIN coaching.study_catalog_outcomes o ON o."Id" = k.outcome_id
LEFT JOIN coaching.study_catalog_topic_outcomes m ON m."TopicId" = k.topic_id AND m."OutcomeId" = k.outcome_id
LEFT JOIN coaching.outcome_duration_estimates e ON e."OutcomeId" = k.outcome_id AND e."IsPublished"
    AND NOT EXISTS (SELECT 1 FROM coaching.outcome_duration_estimates n WHERE n."OutcomeId" = k.outcome_id AND n."IsPublished" AND n."Number" > e."Number")`;
// Read-only files cannot create tables: they use the same rows as common table expressions.
const withState = `WITH km3m AS (\n${dataSelect}),\nkm3m_state AS (\n${stateSelect})`;

const header = (what) => `-- KM3 minutes pack v1 (01.11.2026) — ${what}
-- GENERATED by content-packs/coaching-catalog-km3-minutes/v1/build.mjs from the KM3 model. Do not edit by hand.
-- User decision (01.11.2026, "sınırı yükselt"): a topic may need up to 4320 minutes; topics are not split. The ${rows.length} KM3 topics
-- that releases c1ce79c/5056431e stored at 1440 although their estimate is larger get the uncapped estimate (matched by id).`;

const check = `${header('read-only preview')}
-- Prints one line per topic (code|name|old → new|state) and "km3 minutes check: N to change, N done, N drifted".
--   psql -X -qAt -v ON_ERROR_STOP=1 -f check.sql
BEGIN READ ONLY;
${withState},
lines AS (
SELECT 0 sort, code, code || '|' || coalesce(topic_name, '?') || '|' || old_minutes || ' → ' || new_minutes || '|'
    || CASE WHEN drift IS NOT NULL THEN 'DRIFT: ' || drift WHEN minutes = new_minutes AND notes = new_notes THEN 'done'
            ELSE 'to change' || CASE WHEN estimate_total = old_minutes THEN ' (+ duration version ' || (max_number + 1) || ')' ELSE '' END END line
FROM km3m_state
UNION ALL
SELECT 1, '', 'km3 minutes check: ' || count(*) FILTER (WHERE drift IS NULL AND NOT (minutes = new_minutes AND notes = new_notes)) || ' to change, '
    || count(*) FILTER (WHERE drift IS NULL AND minutes = new_minutes AND notes = new_notes) || ' done, '
    || count(*) FILTER (WHERE drift IS NOT NULL) || ' drifted'
FROM km3m_state)
SELECT line FROM lines ORDER BY sort, code;
COMMIT;
`;

const audit = (action, type, id, path, payload) => `INSERT INTO coaching."AdminAuditRecords" ("Id", "OccurredAt", "ServiceName", "ActorUserId", "ActorRoles", "TenantId",
        "HttpMethod", "Path", "StatusCode", "CorrelationId", "ClientIp", "UserAgent", "Action", "ResourceType", "ResourceId", "ChangedFieldsJson")
    SELECT gen_random_uuid(), now(), 'Coaching', current_setting('km3m.reviewer_id'), 'SystemAdmin', NULL, 'COMMAND', '${path}', 200,
        md5('${PACK}' || txid_current()::text), NULL, '${AGENT}', ${action}, '${type}', ${id}, (${payload})::text`;

const apply = `${header('apply')}
-- In one transaction, matched by topic and outcome id (names are never compared):
--   * topic "EstimatedMinutes" 1440 → the uncapped estimate (at most 4320), and the outcome note's minute sentence to match;
--   * an outcome whose current published duration version totals 1440 (the KM3 pack creates none; the team may have added
--     one) gets a NEW published version (ReviewedStudy, reviewer = -v reviewer_id, next number) with the components and the
--     topic shares scaled to the new total. No version is withdrawn: plans keep the version they use, and the newest
--     published version is the one the planner offers (as the admin panel publication does);
--   * one admin audit record per changed topic (CurriculumInlineEdit) and two per new version (OutcomeEstimate, OutcomePublish).
-- Guards: lock_timeout 5s, the KM3 importer lock and the admin catalog lock; stops with "Nothing changed" without a reviewer,
-- before migration 20261111090000_TopicMinutesCap4320 and when any listed record drifted (other minutes, an edited note,
-- a missing/unapproved link, a published version with another total). Idempotent: a rerun changes nothing.
--   psql -X -qAt -v ON_ERROR_STOP=1 -v reviewer_id=<reviewing admin user id> -f apply.sql   (prints before/changed/after NOTICEs)
\\set ON_ERROR_STOP on
\\if :{?reviewer_id}
\\else
  \\set reviewer_id ''
\\endif
BEGIN;
SET LOCAL lock_timeout = '5s';
SELECT set_config('km3m.reviewer_id', :'reviewer_id', true) AS reviewer \\gset km3m_
DO $$
BEGIN
    IF current_setting('km3m.reviewer_id') !~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
       OR current_setting('km3m.reviewer_id')::uuid = '00000000-0000-0000-0000-000000000000' THEN
        RAISE EXCEPTION 'km3 minutes refused: pass -v reviewer_id=<reviewing admin user id>. Nothing changed.';
    END IF;
END $$;
-- The lock of the KM3 importer (content-packs/coaching-catalog-km3) and the one admin catalog writes take.
SELECT pg_advisory_xact_lock(hashtext('${SOURCE}'));
SELECT pg_advisory_xact_lock(4188, 100);
LOCK TABLE coaching.study_catalog_topics, coaching.study_catalog_outcomes, coaching.study_catalog_topic_outcomes,
    coaching.outcome_duration_estimates, coaching.study_catalog_topic_outcome_shares IN SHARE ROW EXCLUSIVE MODE;
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint c JOIN pg_class r ON r.oid = c.conrelid JOIN pg_namespace n ON n.oid = r.relnamespace
                   WHERE n.nspname = 'coaching' AND r.relname = 'outcome_duration_estimates' AND c.conname = 'ck_outcome_minutes'
                     AND pg_get_constraintdef(c.oid) LIKE '%4320%')
       OR NOT EXISTS (SELECT 1 FROM pg_constraint c JOIN pg_class r ON r.oid = c.conrelid JOIN pg_namespace n ON n.oid = r.relnamespace
                   WHERE n.nspname = 'coaching' AND r.relname = 'study_catalog_topic_outcome_shares' AND c.conname = 'ck_topic_outcome_share_minutes'
                     AND pg_get_constraintdef(c.oid) LIKE '%4320%') THEN
        RAISE EXCEPTION 'km3 minutes refused: the database still limits a topic to 1440 minutes; deploy the coaching service with migration 20261111090000_TopicMinutesCap4320 (limit 4320) first. Nothing changed.';
    END IF;
END $$;

CREATE TEMP TABLE km3m ON COMMIT DROP AS
${dataSelect};
CREATE TEMP TABLE km3m_state ON COMMIT DROP AS
${stateSelect};

-- Largest-remainder split, as OutcomeScopeBudget.Split in the coaching service (ties: earlier index first).
CREATE FUNCTION pg_temp.km3m_split(total integer, weights integer[]) RETURNS integer[] LANGUAGE plpgsql IMMUTABLE AS $f$
DECLARE w bigint[] := weights; s bigint; r integer[] := '{}'; i integer; missing integer;
BEGIN
    SELECT sum(x) INTO s FROM unnest(w) x;
    IF s = 0 THEN w := array_fill(1::bigint, ARRAY[cardinality(weights)]); s := cardinality(weights); END IF;
    FOR i IN 1..cardinality(w) LOOP r := r || (total::bigint * w[i] / s)::integer; END LOOP;
    missing := total - (SELECT sum(x) FROM unnest(r) x);
    FOR i IN SELECT g FROM generate_subscripts(w, 1) g ORDER BY (total::bigint * w[g]) % s DESC, g LIMIT missing LOOP r[i] := r[i] + 1; END LOOP;
    RETURN r;
END $f$;

DO $$
DECLARE problem text;
BEGIN
    RAISE NOTICE 'before: km3 topics at 1440 %, to change %, done %, duration versions to add %',
        (SELECT count(*) FROM coaching.study_catalog_topics WHERE "Source" = '${SOURCE}' AND "EstimatedMinutes" = 1440),
        (SELECT count(*) FROM km3m_state WHERE minutes = old_minutes), (SELECT count(*) FROM km3m_state WHERE minutes = new_minutes),
        (SELECT count(*) FROM km3m_state WHERE estimate_total = old_minutes);
    SELECT string_agg(code || ': ' || drift, '; ' ORDER BY code) INTO problem FROM km3m_state WHERE drift IS NOT NULL;
    IF problem IS NOT NULL THEN
        RAISE EXCEPTION 'km3 minutes refused: stored records differ from the KM3 release (%). Review them in the admin panel. Nothing changed.', left(problem, 1500);
    END IF;
END $$;

CREATE TEMP TABLE km3m_counts (kind text, n bigint) ON COMMIT DROP;

-- 1. Topics and their outcome notes.
WITH changed AS (
    UPDATE coaching.study_catalog_topics t SET "EstimatedMinutes" = s.new_minutes FROM km3m_state s
    WHERE t."Id" = s.topic_id AND t."EstimatedMinutes" = s.old_minutes
    RETURNING t."Id", t."YieldWeight", s.old_minutes, s.new_minutes, s.outcome_id),
audited AS (
    ${audit("'CurriculumInlineEdit'", 'topics', 'c."Id"::text', '/api/coaching-admin/curriculum-management',
      `jsonb_build_object('reason', '${REASON}', 'before', jsonb_build_object('EstimatedMinutes', c.old_minutes, 'YieldWeight', c."YieldWeight"),
            'after', jsonb_build_object('EstimatedMinutes', c.new_minutes, 'YieldWeight', c."YieldWeight"), 'outcomeId', c.outcome_id,
            'outcomeNotes', 'süre cümlesi yeni süreyle güncellendi', 'pack', '${PACK}')`)}
    FROM changed c RETURNING 1)
INSERT INTO km3m_counts SELECT 'topics', count(*) FROM changed UNION ALL SELECT 'audits', count(*) FROM audited;
WITH changed AS (
    UPDATE coaching.study_catalog_outcomes o SET "Notes" = s.new_notes FROM km3m_state s
    WHERE o."Id" = s.outcome_id AND o."Notes" = s.old_notes RETURNING 1)
INSERT INTO km3m_counts SELECT 'notes', count(*) FROM changed;

-- 2. A new published duration version for outcomes the team timed at 1440 (components scaled to the new total).
CREATE TEMP TABLE km3m_versions ON COMMIT DROP AS
SELECT s.outcome_id, s.code, s.estimate_id previous_id, s.estimate_number previous_number, s.max_number + 1 number,
    md5('${PACK}:' || s.outcome_id || ':' || (s.max_number + 1))::uuid id, s.old_minutes, s.new_minutes, s.confidence,
    pg_temp.km3m_split(s.new_minutes, ARRAY[s.learning, s.practice, s."check"]) parts
FROM km3m_state s WHERE s.estimate_total = s.old_minutes;
WITH inserted AS (
    INSERT INTO coaching.outcome_duration_estimates ("Id", "OutcomeId", "Number", "LearningMinutes", "PracticeMinutes", "CheckMinutes",
        "Method", "Confidence", "Evidence", "ReviewedBy", "ReviewedAt", "IsPublished")
    SELECT v.id, v.outcome_id, v.number, v.parts[1], v.parts[2], v.parts[3], 'ReviewedStudy', v.confidence,
        format('KM3 koçluk tahmini (01.11.2026): konu süresi 4320 dakika konu sınırıyla yeniden hesaplandı; önceki sürüm %s (%s dk) → %s dk, '
            || 'bileşenler ve konu payları önceki sürümle orantılı. Önceki sürüm yayında kalır. Kaynak: ${AGENT}.', v.previous_number, v.old_minutes, v.new_minutes),
        current_setting('km3m.reviewer_id')::uuid, now(), true
    FROM km3m_versions v RETURNING 1)
INSERT INTO km3m_counts SELECT 'versions', count(*) FROM inserted;

-- Topic shares of the previous version, each component split over the shares in proportion (ordered by topic id).
CREATE TEMP TABLE km3m_shares ON COMMIT DROP AS
WITH previous AS (
    SELECT v.id estimate_id, v.outcome_id, v.parts, s."TopicId" topic_id, s."ScopeDescription" scope,
        s."LearningMinutes" l, s."PracticeMinutes" p, s."CheckMinutes" c, row_number() OVER (PARTITION BY v.id ORDER BY s."TopicId") i
    FROM km3m_versions v JOIN coaching.study_catalog_topic_outcome_shares s ON s."EstimateId" = v.previous_id),
split AS (
    SELECT estimate_id, pg_temp.km3m_split(min(parts[1]), array_agg(l ORDER BY i)) l, pg_temp.km3m_split(min(parts[2]), array_agg(p ORDER BY i)) p,
        pg_temp.km3m_split(min(parts[3]), array_agg(c ORDER BY i)) c
    FROM previous GROUP BY estimate_id)
SELECT p.topic_id, p.outcome_id, p.estimate_id, x.l[p.i] learning, x.p[p.i] practice, x.c[p.i] "check", p.scope
FROM previous p JOIN split x ON x.estimate_id = p.estimate_id;
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM km3m_shares WHERE learning + practice + "check" < 1) THEN
        RAISE EXCEPTION 'km3 minutes refused: a scaled topic share would get 0 minutes. Nothing changed.';
    END IF;
END $$;
WITH inserted AS (
    INSERT INTO coaching.study_catalog_topic_outcome_shares ("TopicId", "OutcomeId", "EstimateId", "LearningMinutes", "PracticeMinutes",
        "CheckMinutes", "ScopeDescription")
    SELECT topic_id, outcome_id, estimate_id, learning, practice, "check", scope FROM km3m_shares RETURNING 1)
INSERT INTO km3m_counts SELECT 'shares', count(*) FROM inserted;

-- Audit records in the format of the admin outcome service (version created, version published).
WITH audited AS (
    ${audit('a.action', 'StudyOutcome', 'v.id::text', '/api/coaching-admin/outcomes',
      `jsonb_build_object('reason', '${REASON}', 'fingerprint', NULL, 'outcomeId', v.outcome_id, 'number', v.number, 'pack', '${PACK}')`)}
    FROM km3m_versions v CROSS JOIN (VALUES ('OutcomeEstimate'), ('OutcomePublish')) a (action)
    RETURNING 1)
INSERT INTO km3m_counts SELECT 'audits', count(*) FROM audited;

DO $$
DECLARE problem text;
BEGIN
    RAISE NOTICE 'changed: topics %, outcome notes %, duration versions %, topic shares %, audit records %',
        (SELECT n FROM km3m_counts WHERE kind = 'topics'), (SELECT n FROM km3m_counts WHERE kind = 'notes'),
        (SELECT n FROM km3m_counts WHERE kind = 'versions'), (SELECT n FROM km3m_counts WHERE kind = 'shares'),
        (SELECT sum(n) FROM km3m_counts WHERE kind = 'audits');
    SELECT string_agg(k.code, ', ') INTO problem FROM km3m k
    JOIN coaching.study_catalog_topics t ON t."Id" = k.topic_id JOIN coaching.study_catalog_outcomes o ON o."Id" = k.outcome_id
    LEFT JOIN coaching.outcome_duration_estimates e ON e."OutcomeId" = k.outcome_id AND e."IsPublished"
        AND NOT EXISTS (SELECT 1 FROM coaching.outcome_duration_estimates n WHERE n."OutcomeId" = k.outcome_id AND n."IsPublished" AND n."Number" > e."Number")
    WHERE t."EstimatedMinutes" <> k.new_minutes OR o."Notes" <> k.new_notes
       OR (e."Id" IS NOT NULL AND e."LearningMinutes" + e."PracticeMinutes" + e."CheckMinutes" <> k.new_minutes);
    IF problem IS NOT NULL OR (SELECT count(*) FROM km3m) <> ${rows.length} THEN
        RAISE EXCEPTION 'km3 minutes after-check failed (%). Nothing changed.', problem;
    END IF;
    RAISE NOTICE 'after: km3 topics at 1440 %, over 1440 %, max %',
        (SELECT count(*) FROM coaching.study_catalog_topics WHERE "Source" = '${SOURCE}' AND "EstimatedMinutes" = 1440),
        (SELECT count(*) FROM coaching.study_catalog_topics WHERE "Source" = '${SOURCE}' AND "EstimatedMinutes" > 1440),
        (SELECT max("EstimatedMinutes") FROM coaching.study_catalog_topics WHERE "Source" = '${SOURCE}');
END $$;
COMMIT;
`;

const verify = `${header('read-only verification after apply.sql')}
-- Fails unless every listed topic holds its new minutes and note and each timed outcome's newest published version has the
-- new total; prints "km3 minutes verify: ok".
--   psql -X -qAt -v ON_ERROR_STOP=1 -f verify.sql
BEGIN READ ONLY;
DO $$
DECLARE problem text;
BEGIN
    ${withState}
    SELECT string_agg(code || ': ' || coalesce(drift, 'minutes ' || minutes || ', note ' || CASE WHEN notes = new_notes THEN 'new' ELSE 'old' END
        || coalesce(', duration version total ' || estimate_total, '')), '; ' ORDER BY code) INTO problem
    FROM km3m_state
    WHERE drift IS NOT NULL OR minutes <> new_minutes OR notes <> new_notes OR (estimate_id IS NOT NULL AND estimate_total <> new_minutes);
    IF problem IS NULL AND EXISTS (SELECT 1 FROM coaching.study_catalog_topics WHERE "Source" = '${SOURCE}' AND "EstimatedMinutes" > 4320) THEN
        problem := 'a KM3 topic is above 4320 minutes';
    END IF;
    IF problem IS NOT NULL THEN RAISE EXCEPTION 'km3 minutes verify failed: %', left(problem, 1500); END IF;
END $$;
SELECT 'km3 minutes verify: ok';
COMMIT;
`;

const table = ['| Konu | Sınav | Ad | Önce | Sonra |', '| --- | --- | --- | ---: | ---: |']
  .concat(rows.map(t => `| \`${t.code}\` | ${t.exam} | ${t.name} | ${t.previousMinutes} | ${t.minutes} |`)).join('\n');
const readmePath = dir + 'README.md';
const readme = readFileSync(readmePath, 'utf8');
const outputs = { 'topics.csv': csv, 'check.sql': check, 'apply.sql': apply, 'verify.sql': verify,
  'README.md': readme.replace(/<!-- topics:start -->[\s\S]*<!-- topics:end -->/, `<!-- topics:start -->\n${table}\n<!-- topics:end -->`) };

if (process.argv[2] === '--check') {
  const stale = Object.entries(outputs).filter(([name, text]) => { try { return readFileSync(dir + name, 'utf8') !== text; } catch { return true; } }).map(([n]) => n);
  if (stale.length) { console.error(`out of date: ${stale.join(', ')} — run node content-packs/coaching-catalog-km3-minutes/v1/build.mjs`); process.exit(1); }
} else {
  for (const [name, text] of Object.entries(outputs)) writeFileSync(dir + name, text);
  console.log(`${rows.length} topics: ${rows.reduce((s, t) => s + t.previousMinutes, 0)} → ${rows.reduce((s, t) => s + t.minutes, 0)} minutes`);
}
