CREATE TEMP TABLE km8_topics ON COMMIT DROP AS
    SELECT t."Id" AS id, t."ParentId" AS parent_id, t."UnitId" AS unit_id, t."LessonId" AS lesson_id
    FROM coaching.study_catalog_topics t WHERE t."LessonId" IN (SELECT id FROM km8_list);
CREATE TEMP TABLE km8_units ON COMMIT DROP AS
    SELECT u."Id" AS id, u."LessonId" AS lesson_id FROM coaching.study_catalog_units u WHERE u."LessonId" IN (SELECT id FROM km8_list);
CREATE TEMP TABLE km8_lessons ON COMMIT DROP AS
    SELECT l."Id" AS id FROM coaching.study_catalog_lessons l WHERE l."Id" IN (SELECT id FROM km8_list);
CREATE TEMP TABLE km8_exam_answers ON COMMIT DROP AS
    SELECT COALESCE(item->>'LessonId', item->>'lessonId')::uuid AS lesson_id, COALESCE(item->>'TopicId', item->>'topicId')::uuid AS topic_id
    FROM coaching.exam_results r
    CROSS JOIN LATERAL jsonb_array_elements(CASE WHEN jsonb_typeof(r.lesson_answers) = 'array' THEN r.lesson_answers ELSE '[]'::jsonb END) item;
CREATE TEMP TABLE km8_used_topics (id uuid PRIMARY KEY) ON COMMIT DROP;
INSERT INTO km8_used_topics
    WITH RECURSIVE direct AS (
        SELECT "TopicId" AS id FROM coaching.student_topic_states
        UNION SELECT "TopicId" FROM coaching.study_plan_tasks WHERE "TopicId" IS NOT NULL
        UNION SELECT topic_id FROM km8_exam_answers WHERE topic_id IS NOT NULL
        UNION SELECT COALESCE(item->>'TopicId', item->>'topicId')::uuid
            FROM coaching.exam_results r
            CROSS JOIN LATERAL jsonb_array_elements(CASE WHEN jsonb_typeof(COALESCE(r.topic_analysis->'Topics', r.topic_analysis->'topics')) = 'array'
                THEN COALESCE(r.topic_analysis->'Topics', r.topic_analysis->'topics') ELSE '[]'::jsonb END) item),
    up AS (
        SELECT t.id, t.parent_id FROM km8_topics t WHERE t.id IN (SELECT id FROM direct)
        UNION SELECT p.id, p.parent_id FROM km8_topics p JOIN up ON up.parent_id = p.id)
    SELECT DISTINCT id FROM up;
CREATE TEMP TABLE km8_used_units (id uuid PRIMARY KEY) ON COMMIT DROP;
INSERT INTO km8_used_units SELECT DISTINCT unit_id FROM km8_topics WHERE id IN (SELECT id FROM km8_used_topics);
CREATE TEMP TABLE km8_used_lessons (id uuid PRIMARY KEY) ON COMMIT DROP;
INSERT INTO km8_used_lessons
    SELECT id FROM km8_lessons l WHERE
        EXISTS (SELECT 1 FROM coaching.student_course_preferences c WHERE c."LessonId" = l.id)
        OR EXISTS (SELECT 1 FROM coaching.study_plan_tasks p WHERE p."WeeklyLessonId" = l.id)
        OR EXISTS (SELECT 1 FROM coaching.study_weekly_drafts d
            CROSS JOIN LATERAL jsonb_array_elements(CASE WHEN jsonb_typeof(d."SlotsJson") = 'array' THEN d."SlotsJson" ELSE '[]'::jsonb END) item
            WHERE COALESCE(item->>'LessonId', item->>'lessonId')::uuid = l.id)
        OR EXISTS (SELECT 1 FROM km8_exam_answers a WHERE a.lesson_id = l.id)
        OR EXISTS (SELECT 1 FROM km8_units u WHERE u.lesson_id = l.id AND u.id IN (SELECT id FROM km8_used_units));

-- Rows this run deletes / deactivates (a used row that is already passive is left alone).
CREATE TEMP TABLE km8_actions (kind text NOT NULL, id uuid NOT NULL, action text NOT NULL, PRIMARY KEY (kind, id)) ON COMMIT DROP;
INSERT INTO km8_actions
    SELECT 'Lessons', l."Id", CASE WHEN l."Id" IN (SELECT id FROM km8_used_lessons) THEN 'deactivated' ELSE 'deleted' END
    FROM coaching.study_catalog_lessons l WHERE l."Id" IN (SELECT id FROM km8_lessons) AND (l."IsActive" OR l."Id" NOT IN (SELECT id FROM km8_used_lessons))
    UNION ALL
    SELECT 'Units', u."Id", CASE WHEN u."Id" IN (SELECT id FROM km8_used_units) THEN 'deactivated' ELSE 'deleted' END
    FROM coaching.study_catalog_units u WHERE u."Id" IN (SELECT id FROM km8_units) AND (u."IsActive" OR u."Id" NOT IN (SELECT id FROM km8_used_units))
    UNION ALL
    SELECT 'Topics', t."Id", CASE WHEN t."Id" IN (SELECT id FROM km8_used_topics) THEN 'deactivated' ELSE 'deleted' END
    FROM coaching.study_catalog_topics t WHERE t."Id" IN (SELECT id FROM km8_topics) AND (t."IsActive" OR t."Id" NOT IN (SELECT id FROM km8_used_topics));

DO $$
DECLARE
    keep_before text; keep_after text; n_audit integer; actor text;
    d_lessons integer; d_units integer; d_topics integer; step integer;
    reason constant text := 'KM8: koçluk kataloğu yalnız sınav derslerini tutar (kullanıcı kararı 01.11.2026). Kullanılmayan okul dersi kalıcı silindi; öğrenci verisinde kullanılan pasife alındı.';
BEGIN
    actor := coalesce(nullif(current_setting('km8.actor', true), ''), 'content-pack/' || current_user);
    RAISE NOTICE 'before: lessons % (exam-less %, active %), units %, topics %',
        (SELECT count(*) FROM coaching.study_catalog_lessons), (SELECT count(*) FROM coaching.study_catalog_lessons WHERE "ExamCode" IS NULL),
        (SELECT count(*) FROM coaching.study_catalog_lessons WHERE "ExamCode" IS NULL AND "IsActive"),
        (SELECT count(*) FROM coaching.study_catalog_units), (SELECT count(*) FROM coaching.study_catalog_topics);
    -- Everything that is not on the list must come out unchanged.
    SELECT md5(string_agg(x, '|' ORDER BY x)) INTO keep_before FROM (
        SELECT l::text x FROM coaching.study_catalog_lessons l WHERE l."Id" NOT IN (SELECT id FROM km8_list)
        UNION ALL SELECT u::text FROM coaching.study_catalog_units u WHERE u."LessonId" NOT IN (SELECT id FROM km8_list)
        UNION ALL SELECT t::text FROM coaching.study_catalog_topics t WHERE t."LessonId" NOT IN (SELECT id FROM km8_list)) rows;

    -- 1. Back up every row this run changes, with all its columns (a row restored earlier is backed up afresh).
    DELETE FROM coaching.removed_school_catalog_20261101_lessons b USING km8_actions a WHERE a.kind = 'Lessons' AND a.id = b."Id" AND b."RemovalAction" = 'restored';
    DELETE FROM coaching.removed_school_catalog_20261101_units b USING km8_actions a WHERE a.kind = 'Units' AND a.id = b."Id" AND b."RemovalAction" = 'restored';
    DELETE FROM coaching.removed_school_catalog_20261101_topics b USING km8_actions a WHERE a.kind = 'Topics' AND a.id = b."Id" AND b."RemovalAction" = 'restored';
    -- A row deactivated by an earlier run keeps its original backup (IsActive as it was); only its action moves to 'deleted'.
    INSERT INTO coaching.removed_school_catalog_20261101_lessons AS b
        SELECT l.*, a.action, now() FROM coaching.study_catalog_lessons l JOIN km8_actions a ON a.kind = 'Lessons' AND a.id = l."Id"
        ON CONFLICT ("Id") DO UPDATE SET "RemovalAction" = EXCLUDED."RemovalAction", "RemovedAt" = EXCLUDED."RemovedAt"
        WHERE b."RemovalAction" = 'deactivated' AND EXCLUDED."RemovalAction" = 'deleted';
    INSERT INTO coaching.removed_school_catalog_20261101_units AS b
        SELECT u.*, a.action, now() FROM coaching.study_catalog_units u JOIN km8_actions a ON a.kind = 'Units' AND a.id = u."Id"
        ON CONFLICT ("Id") DO UPDATE SET "RemovalAction" = EXCLUDED."RemovalAction", "RemovedAt" = EXCLUDED."RemovedAt"
        WHERE b."RemovalAction" = 'deactivated' AND EXCLUDED."RemovalAction" = 'deleted';
    INSERT INTO coaching.removed_school_catalog_20261101_topics AS b
        SELECT t.*, a.action, now() FROM coaching.study_catalog_topics t JOIN km8_actions a ON a.kind = 'Topics' AND a.id = t."Id"
        ON CONFLICT ("Id") DO UPDATE SET "RemovalAction" = EXCLUDED."RemovalAction", "RemovedAt" = EXCLUDED."RemovedAt"
        WHERE b."RemovalAction" = 'deactivated' AND EXCLUDED."RemovalAction" = 'deleted';

    -- 2. Audit records, in the format of the admin catalog writes (CoachingCatalogDeletionService / CoachingCatalogManagementService).
    INSERT INTO coaching."AdminAuditRecords" ("Id", "OccurredAt", "ServiceName", "ActorUserId", "ActorRoles", "TenantId", "HttpMethod", "Path",
        "StatusCode", "CorrelationId", "ClientIp", "UserAgent", "Action", "ResourceType", "ResourceId", "ChangedFieldsJson")
    SELECT gen_random_uuid(), now(), 'Coaching', actor, 'SystemAdmin', NULL,
        CASE WHEN a.action = 'deleted' THEN 'DELETE' ELSE 'PUT' END, format('/api/coaching-admin/catalog/%s/%s', a.kind, a.id), 200,
        replace(md5('km8-school-lessons-removal' || txid_current()::text), '-', ''), NULL, 'content-packs/school-lessons-removal/v1',
        CASE WHEN a.action = 'deleted' THEN 'CatalogPermanentDelete' ELSE 'CatalogStatus' END, a.kind, a.id::text,
        CASE WHEN a.action = 'deleted'
            THEN jsonb_build_object('reason', reason, 'name', r.name, 'source', r.source, 'sourceId', r.source_id, 'pack', 'school-lessons-removal/v1')
            ELSE jsonb_build_object('reason', reason, 'isActive', false, 'name', r.name, 'source', r.source, 'sourceId', r.source_id, 'pack', 'school-lessons-removal/v1') END::text
    FROM km8_actions a
    JOIN (SELECT 'Lessons' AS kind, "Id" AS id, "Name" AS name, "Source" AS source, "SourceId" AS source_id FROM coaching.study_catalog_lessons
        UNION ALL SELECT 'Units', "Id", "Name", "Source", "SourceId" FROM coaching.study_catalog_units
        UNION ALL SELECT 'Topics', "Id", "Name", "Source", "SourceId" FROM coaching.study_catalog_topics) r ON r.kind = a.kind AND r.id = a.id;
    GET DIAGNOSTICS n_audit = ROW_COUNT;

    -- 3. Delete unused rows: topics (leaves first), then units, then lessons.
    d_topics := 0;
    LOOP
        DELETE FROM coaching.study_catalog_topics t
        WHERE t."Id" IN (SELECT id FROM km8_actions WHERE kind = 'Topics' AND action = 'deleted')
            AND NOT EXISTS (SELECT 1 FROM coaching.study_catalog_topics c WHERE c."ParentId" = t."Id");
        GET DIAGNOSTICS step = ROW_COUNT;
        EXIT WHEN step = 0;
        d_topics := d_topics + step;
    END LOOP;
    DELETE FROM coaching.study_catalog_units WHERE "Id" IN (SELECT id FROM km8_actions WHERE kind = 'Units' AND action = 'deleted');
    GET DIAGNOSTICS d_units = ROW_COUNT;
    DELETE FROM coaching.study_catalog_lessons WHERE "Id" IN (SELECT id FROM km8_actions WHERE kind = 'Lessons' AND action = 'deleted');
    GET DIAGNOSTICS d_lessons = ROW_COUNT;
    IF d_topics <> (SELECT count(*) FROM km8_actions WHERE kind = 'Topics' AND action = 'deleted')
        OR d_units <> (SELECT count(*) FROM km8_actions WHERE kind = 'Units' AND action = 'deleted')
        OR d_lessons <> (SELECT count(*) FROM km8_actions WHERE kind = 'Lessons' AND action = 'deleted') THEN
        RAISE EXCEPTION 'Could not delete every unused row (topics %, units %, lessons %). Nothing changed.', d_topics, d_units, d_lessons;
    END IF;
    RAISE NOTICE 'deleted: lessons %, units %, topics %', d_lessons, d_units, d_topics;

    -- 4. Deactivate the used ones.
    UPDATE coaching.study_catalog_topics SET "IsActive" = false WHERE "Id" IN (SELECT id FROM km8_actions WHERE kind = 'Topics' AND action = 'deactivated');
    UPDATE coaching.study_catalog_units SET "IsActive" = false WHERE "Id" IN (SELECT id FROM km8_actions WHERE kind = 'Units' AND action = 'deactivated');
    UPDATE coaching.study_catalog_lessons SET "IsActive" = false WHERE "Id" IN (SELECT id FROM km8_actions WHERE kind = 'Lessons' AND action = 'deactivated');
    RAISE NOTICE 'deactivated: lessons %, units %, topics %',
        (SELECT count(*) FROM km8_actions WHERE kind = 'Lessons' AND action = 'deactivated'),
        (SELECT count(*) FROM km8_actions WHERE kind = 'Units' AND action = 'deactivated'),
        (SELECT count(*) FROM km8_actions WHERE kind = 'Topics' AND action = 'deactivated');

    -- 5. After-checks: no exam-less lesson, unit or topic stays active; the exam lessons are untouched.
    SELECT md5(string_agg(x, '|' ORDER BY x)) INTO keep_after FROM (
        SELECT l::text x FROM coaching.study_catalog_lessons l WHERE l."Id" NOT IN (SELECT id FROM km8_list)
        UNION ALL SELECT u::text FROM coaching.study_catalog_units u WHERE u."LessonId" NOT IN (SELECT id FROM km8_list)
        UNION ALL SELECT t::text FROM coaching.study_catalog_topics t WHERE t."LessonId" NOT IN (SELECT id FROM km8_list)) rows;
    IF keep_after IS DISTINCT FROM keep_before THEN RAISE EXCEPTION 'An exam lesson changed. Nothing changed.'; END IF;
    IF EXISTS (SELECT 1 FROM coaching.study_catalog_lessons WHERE "ExamCode" IS NULL AND "IsActive")
        OR EXISTS (SELECT 1 FROM coaching.study_catalog_units WHERE "LessonId" IN (SELECT id FROM km8_list) AND "IsActive")
        OR EXISTS (SELECT 1 FROM coaching.study_catalog_topics WHERE "LessonId" IN (SELECT id FROM km8_list) AND "IsActive") THEN
        RAISE EXCEPTION 'A school lesson, unit or topic is still active. Nothing changed.';
    END IF;
    RAISE NOTICE 'after: lessons % (exam-less %, active %), units %, topics %',
        (SELECT count(*) FROM coaching.study_catalog_lessons), (SELECT count(*) FROM coaching.study_catalog_lessons WHERE "ExamCode" IS NULL),
        (SELECT count(*) FROM coaching.study_catalog_lessons WHERE "ExamCode" IS NULL AND "IsActive"),
        (SELECT count(*) FROM coaching.study_catalog_units), (SELECT count(*) FROM coaching.study_catalog_topics);
    RAISE NOTICE 'audit: % record(s); backups: lessons %, units %, topics %', n_audit,
        (SELECT count(*) FROM coaching.removed_school_catalog_20261101_lessons), (SELECT count(*) FROM coaching.removed_school_catalog_20261101_units),
        (SELECT count(*) FROM coaching.removed_school_catalog_20261101_topics);
END $$;

COMMIT;
