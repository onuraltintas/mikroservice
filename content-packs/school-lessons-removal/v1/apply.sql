-- Backup tables: the catalog table's columns (LIKE), plus what this pack did and when.
DO $$
DECLARE kind text;
BEGIN
    FOREACH kind IN ARRAY ARRAY['lessons', 'units', 'topics'] LOOP
        IF to_regclass(format('coaching.removed_school_catalog_20261101_%s', kind)) IS NULL THEN
            EXECUTE format('CREATE TABLE coaching.removed_school_catalog_20261101_%1$s (LIKE coaching.study_catalog_%1$s INCLUDING DEFAULTS)', kind);
            EXECUTE format('ALTER TABLE coaching.removed_school_catalog_20261101_%s ADD PRIMARY KEY ("Id"),
                ADD COLUMN "RemovalAction" varchar(20) NOT NULL CHECK ("RemovalAction" IN (''deleted'', ''deactivated'', ''restored'')),
                ADD COLUMN "RemovedAt" timestamp with time zone NOT NULL', kind);
            EXECUTE format('COMMENT ON TABLE coaching.removed_school_catalog_20261101_%s IS %L', kind,
                'KM8 content-packs/school-lessons-removal/v1: catalog rows as they were before the pack deleted or deactivated them. restore.sql reads this table.');
        END IF;
    END LOOP;
END $$;

-- Drift guard.
DO $$
DECLARE reasons text;
BEGIN
    SELECT string_agg(reason, '; ' ORDER BY ord, reason) INTO reasons FROM (
        SELECT 1 AS ord, format('%s %s is missing (not in the catalog and not removed by this pack)', list.id, list.name) AS reason
        FROM km8_list list WHERE NOT EXISTS (SELECT 1 FROM coaching.study_catalog_lessons l WHERE l."Id" = list.id)
            AND NOT EXISTS (SELECT 1 FROM coaching.removed_school_catalog_20261101_lessons b WHERE b."Id" = list.id AND b."RemovalAction" = 'deleted')
        UNION ALL SELECT 2, format('%s was renamed to "%s" (list: "%s")', l."Id", l."Name", list.name)
        FROM coaching.study_catalog_lessons l JOIN km8_list list ON list.id = l."Id" WHERE l."Name" <> list.name
        UNION ALL SELECT 3, format('%s %s has the exam code %s', l."Id", l."Name", l."ExamCode")
        FROM coaching.study_catalog_lessons l JOIN km8_list list ON list.id = l."Id" WHERE l."ExamCode" IS NOT NULL
        UNION ALL SELECT 4, format('%s %s has no exam code and is not on the list', l."Id", l."Name")
        FROM coaching.study_catalog_lessons l WHERE l."ExamCode" IS NULL AND l."Id" NOT IN (SELECT id FROM km8_list)
        UNION ALL SELECT 5, format('outcome links, program bindings or YKS scopes on listed lessons: %s', n)
        FROM (SELECT (SELECT count(*) FROM coaching.study_catalog_topic_outcomes m JOIN coaching.study_catalog_topics t ON t."Id" = m."TopicId" WHERE t."LessonId" IN (SELECT id FROM km8_list))
            + (SELECT count(*) FROM coaching.study_catalog_topic_outcome_shares s JOIN coaching.study_catalog_topics t ON t."Id" = s."TopicId" WHERE t."LessonId" IN (SELECT id FROM km8_list))
            + (SELECT count(*) FROM coaching.study_catalog_yks_scopes s JOIN coaching.study_catalog_topics t ON t."Id" = s."TopicId" WHERE t."LessonId" IN (SELECT id FROM km8_list))
            + (SELECT count(*) FROM coaching.official_curriculum_lesson_bindings b WHERE b."LessonId" IN (SELECT id FROM km8_list)) AS n) x WHERE n > 0
        UNION ALL SELECT 6, format('topic %s of a listed lesson has a parent or child outside it', t."Id")
        FROM coaching.study_catalog_topics t JOIN coaching.study_catalog_topics p ON p."Id" = t."ParentId"
        WHERE (t."LessonId" IN (SELECT id FROM km8_list)) <> (p."LessonId" IN (SELECT id FROM km8_list))) drift;
    IF reasons IS NOT NULL THEN
        RAISE EXCEPTION 'School lesson list drifted: %. Nothing changed. Run check.sql and report it before deciding.', reasons;
    END IF;
END $$;

