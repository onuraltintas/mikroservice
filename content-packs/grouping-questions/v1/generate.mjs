// Kelime Gruplama paket metinleri için 4'er anlama sorusu (26.11.2026).
// Her öykünün soru havuzundaki her soru, cevabının bulunduğu son paragrafla etiketlidir (need). Bir metin seçkisi
// öykünün ilk N paragrafıdır; ona yalnız need <= N olan sorular düşer. Uzun seçkilerde (N >= 12) ilk üçte birdeki
// sorular atlanır; kalanlar arasından seçkinin baştan sonuna yayılan 4 soru seçilir.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const directory = dirname(fileURLToPath(import.meta.url));
const groupingPack = resolve(directory, '../../grouping/v1');
const texts = JSON.parse(readFileSync(join(groupingPack, 'content.json'), 'utf8'));
const banks = Object.fromEntries(['library', 'garden', 'map'].map(name =>
  [name, JSON.parse(readFileSync(join(directory, `banks/${name}.json`), 'utf8')).questions]));

export function paragraphs(content) { return content.trim().split(/\r?\n\s*\r?\n/u).length; }

export function pick(bank, count) {
  let eligible = bank.filter(question => question.need <= count);
  if (count >= 12) {
    const later = eligible.filter(question => question.need >= count / 3);
    if (later.length >= 4) eligible = later;
  }
  if (eligible.length < 4) throw new Error(`Only ${eligible.length} questions for ${count} paragraphs`);
  return [0, 1, 2, 3].map(index => eligible[Math.round(index * (eligible.length - 1) / 3)]);
}

const rows = [];
let serial = 0;
for (const text of texts) {
  const source = text.source.replace(/^texts\//u, '').replace(/\.txt$/u, '');
  const chosen = pick(banks[source], paragraphs(text.content));
  chosen.forEach((question, orderIndex) => {
    serial++;
    rows.push({
      id: `d7b30000-0000-5000-8000-${String(serial).padStart(12, '0')}`,
      readingTextId: text.id, contentMd5: createHash('md5').update(text.content, 'utf8').digest('hex'),
      key: question.key, questionText: question.text, type: question.type, bloomLevel: question.bloom,
      difficultyLevel: text.level, explanation: question.explanation,
      optionA: question.options[0], optionB: question.options[1], optionC: question.options[2], optionD: question.options[3],
      correctAnswer: question.answer, orderIndex
    });
  });
}

const sql = value => value === null ? 'NULL' : typeof value === 'number' ? String(value) : `'${String(value).replaceAll("'", "''")}'`;
const textChecks = [...new Map(rows.map(row => [row.readingTextId, row.contentMd5])).entries()];
const apply = `-- Generated by content-packs/grouping-questions/v1/generate.mjs. Do not edit by hand.
-- Adds four comprehension questions to each of the 60 Kelime Gruplama pack texts (content-packs/grouping/v1).
-- Stops without changes unless all 60 texts exist unchanged (content md5). Safe to rerun: deterministic ids, existing rows skipped.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '60s';

CREATE TEMP TABLE grouping_text_check (id uuid PRIMARY KEY, content_md5 text NOT NULL) ON COMMIT DROP;
INSERT INTO grouping_text_check (id, content_md5) VALUES
${textChecks.map(([id, md5]) => `    ('${id}'::uuid, '${md5}')`).join(',\n')};

DO $$
DECLARE matched integer;
BEGIN
    SELECT count(*) INTO matched FROM grouping_text_check c
    JOIN speed_reading.reading_texts t ON t.id = c.id AND NOT t.is_deleted AND md5(t.content) = c.content_md5;
    IF matched <> ${textChecks.length} THEN
        RAISE EXCEPTION 'grouping-questions/v1: % of ${textChecks.length} pack texts match; nothing changed', matched;
    END IF;
END $$;

CREATE TEMP TABLE grouping_question_pack (
    id uuid PRIMARY KEY, reading_text_id uuid NOT NULL, question_text text NOT NULL, type integer NOT NULL,
    bloom_level integer NOT NULL, difficulty_level integer NOT NULL, explanation text NOT NULL,
    option_a text NOT NULL, option_b text NOT NULL, option_c text NOT NULL, option_d text NOT NULL,
    correct_answer text NOT NULL, order_index integer NOT NULL
) ON COMMIT DROP;
INSERT INTO grouping_question_pack
    (id, reading_text_id, question_text, type, bloom_level, difficulty_level, explanation,
     option_a, option_b, option_c, option_d, correct_answer, order_index)
VALUES
${rows.map(row => `    ('${row.id}'::uuid, '${row.readingTextId}'::uuid, ${sql(row.questionText)}, ${row.type}, ${row.bloomLevel}, ${row.difficultyLevel}, ${sql(row.explanation)},
     ${sql(row.optionA)}, ${sql(row.optionB)}, ${sql(row.optionC)}, ${sql(row.optionD)}, ${sql(row.correctAnswer)}, ${row.orderIndex})`).join(',\n')};

DO $$
DECLARE added integer;
BEGIN
    INSERT INTO speed_reading.reading_questions
        (id, reading_text_id, question_text, type, bloom_level, difficulty_level, explanation,
         option_a, option_b, option_c, option_d, correct_answer, order_index, created_at, created_by, is_deleted)
    SELECT id, reading_text_id, question_text, type, bloom_level, difficulty_level, explanation,
           option_a, option_b, option_c, option_d, correct_answer, order_index, CURRENT_TIMESTAMP, 'grouping-questions-v1', FALSE
    FROM grouping_question_pack source
    WHERE NOT EXISTS (SELECT 1 FROM speed_reading.reading_questions target WHERE target.id = source.id);
    GET DIAGNOSTICS added = ROW_COUNT;
    RAISE NOTICE 'grouping-questions/v1: % question(s) added', added;
END $$;

COMMIT;
`;
const rollback = `-- Generated by content-packs/grouping-questions/v1/generate.mjs. Do not edit by hand.
-- Soft-deletes only the ${rows.length} deterministic questions created by grouping-questions/v1.
BEGIN;
DO $$
DECLARE removed integer;
BEGIN
    UPDATE speed_reading.reading_questions
    SET is_deleted = TRUE, deleted_at = CURRENT_TIMESTAMP, deleted_by = 'grouping-questions-v1-rollback',
        updated_at = CURRENT_TIMESTAMP, updated_by = 'grouping-questions-v1-rollback'
    WHERE NOT is_deleted AND created_by = 'grouping-questions-v1' AND id IN (
${rows.map(row => `        '${row.id}'::uuid`).join(',\n')});
    GET DIAGNOSTICS removed = ROW_COUNT;
    RAISE NOTICE 'grouping-questions/v1 rollback: % question(s) soft-deleted', removed;
END $$;
COMMIT;
`;
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(join(directory, 'questions.json'), JSON.stringify(rows, null, 2) + '\n');
  writeFileSync(join(directory, 'apply.sql'), apply);
  writeFileSync(join(directory, 'rollback.sql'), rollback);
  console.log(`Generated ${rows.length} questions for ${textChecks.length} texts.`);
}
