import {mkdirSync,copyFileSync,readFileSync,writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
const root=resolve('artifacts/coaching-development-live-20261020-r1'),pack=resolve(root,'api-fix-package');
mkdirSync(pack,{recursive:true});
for(const name of ['Coaching.Infrastructure.dll','Coaching.Infrastructure.pdb','Probe.dll']) copyFileSync(resolve(root,'probe-publish',name),resolve(pack,name));
const hash=file=>createHash('sha256').update(readFileSync(file)).digest('hex');
writeFileSync(resolve(pack,'payload.sha256'),['Coaching.Infrastructure.dll','Coaching.Infrastructure.pdb','Probe.dll'].map(name=>hash(resolve(pack,name))+'  '+name).join('\n')+'\n');
execFileSync('tar',['-czf',resolve(root,'api-fix.tar.gz'),'-C',pack,'.']);
writeFileSync(resolve(root,'api-fix-archive.sha256'),hash(resolve(root,'api-fix.tar.gz'))+'  api-fix.tar.gz\n');
console.log(readFileSync(resolve(root,'api-fix-archive.sha256'),'utf8').trim());
