import {cpSync,existsSync,mkdirSync,readFileSync,writeFileSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
import {resolve,basename} from 'node:path';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
const root=process.cwd(),name='coaching-yearly-calendar-live-20261017';
const release=resolve(root,'artifacts',name),previous=resolve(root,'artifacts/coaching-weekly-outcomes-live-20261017-r2');
const revision='1e7c488f',base='5411fc01';
const git=(...args)=>execFileSync('git',args,{cwd:root,maxBuffer:32*1024*1024});
assert.ok(!existsSync(resolve(release,'admin-source')),'Preserve prepared releases.');
assert.equal(JSON.parse(readFileSync(resolve(previous,'source-provenance.json'))).revision,git('rev-parse',base).toString().trim());
const files=git('diff','--name-only',base,revision,'--','clients/admin-panel/src').toString().trim().split('\n').filter(x=>!x.endsWith('.spec.ts'));
assert.equal(files.length,7);assert.ok(files.every(x=>x.startsWith('clients/admin-panel/src/app/features/coaching-portal/pages/')));
mkdirSync(release,{recursive:true});
cpSync(resolve(previous,'admin-source'),resolve(release,'admin-source'),{recursive:true,filter:p=>!/[\\/](node_modules|dist|\.angular|bin|obj|\.git)([\\/]|$)/.test(p)&&!basename(p).startsWith('.env')});
for(const file of files)execFileSync('git',['apply','--recount','--directory=artifacts/'+name+'/admin-source','-'],{cwd:root,input:git('diff','--binary',base,revision,'--',file)});
const sha=p=>createHash('sha256').update(readFileSync(p)).digest('hex');
assert.equal(sha(resolve(previous,'admin-source/clients/admin-panel/package-lock.json')),sha(resolve(root,'clients/admin-panel/package-lock.json')));
writeFileSync(resolve(release,'source-provenance.json'),JSON.stringify({revision:git('rev-parse',revision).toString().trim(),baseRevision:git('rev-parse',base).toString().trim(),previousRelease:'coaching-weekly-outcomes-20261017-r2',services:['admin-panel'],databaseMigration:false,files},null,2));
console.log(JSON.stringify({release,files,revision}));
